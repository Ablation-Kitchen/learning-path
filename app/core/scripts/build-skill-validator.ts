/**
 * Bundles the app's path loader into the `learning-path` skill as one dependency-free file
 * (yaml, ajv and the schema inlined), so the skill checks paths exactly as the app does.
 *
 *   npm run build:skill-validator
 *
 * Output: <repo>/plugins/learning-path/skills/learning-path/scripts/validate.mjs. A test fails when the committed
 * file is out of date, so rerun this after any change to the schema or the loader.
 */
import { build } from "esbuild";
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const coreDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const SKILL_VALIDATOR = resolve(
  coreDir,
  "../../plugins/learning-path/skills/learning-path/scripts/validate.mjs",
);

const BANNER = `// GENERATED by app/core/scripts/build-skill-validator.ts from the app's path loader.
// Do not edit: run \`npm run build:skill-validator -w core\` in app/ instead.
// Usage: node validate.mjs <path-file.yaml> [more files...]   (Node 18+, no dependencies)
import { createRequire as __createRequire } from "node:module";
const require = __createRequire(import.meta.url);`;

export async function bundleSkillValidator(): Promise<string> {
  const result = await build({
    entryPoints: [resolve(coreDir, "scripts/skill-validator-entry.ts")],
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node18",
    write: false,
    minify: true,
    legalComments: "none",
    banner: { js: BANNER },
    logLevel: "silent",
  });
  return result.outputFiles[0]!.text;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(SKILL_VALIDATOR, await bundleSkillValidator());
  console.log(`wrote ${SKILL_VALIDATOR}`);
}
